<h1>Tekst test</h1>

<h2>Wat is er verkeerd?</h2>

<h3>AI in scholen kunnen helpen in kennis</h3>

<p>
    De afgelopen jaren is het gebruik van kunstmatige intelligentie (AI) in het onderwijs sterk toegenomen. Scholen gebruiken AI onder andere voor het nakijken van opdrachten,
    het maken van oefentoetsen en het geven van persoonlijke feedback aan leerlingen. Uit een onderzoek onder 150 middelbare scholen blijkt
    dat ongeveer 35% van de scholen experimenteert met AI-tools in de klas.
</p>

<p>
    Volgens de onderzoekers kan AI bepaalde taken van leraren ondersteunen, waardoor zij meer tijd overhouden voor individuele begeleiding van leerlingen.
    Verschillende scholen geven aan dat AI vooral wordt ingezet als hulpmiddel en niet als vervanging van docenten.
    Leerlingen kunnen bijvoorbeeld extra uitleg krijgen over een onderwerp of automatisch gegenereerde oefenvragen maken.
</p>

<h3>AI problemen</h3>

<p>
    Toch zijn er ook zorgen. Onderwijsexperts waarschuwen dat AI soms onjuiste informatie kan geven en dat leerlingen kritisch moeten blijven nadenken over de antwoorden
    die zij ontvangen. Daarnaast benadrukken zij dat sociale interactie, motivatie en persoonlijke begeleiding belangrijke onderdelen van onderwijs zijn
    die niet eenvoudig door technologie kunnen worden overgenomen.
</p>

<p>
    De onderzoekers concluderen daarom dat AI waarschijnlijk een grotere rol zal spelen in het onderwijs, maar dat er momenteel geen aanwijzingen zijn
    dat scholen van plan zijn om leraren op grote schaal te vervangen.
</p>
